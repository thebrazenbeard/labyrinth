"""Approved training-only program challenges with *semantic* specificity.

Unlike a simple room-count multiplier, specificity narrows which executable
register-program concepts are exercised. The current public generator offers
only four training structures, so this module deliberately supports only a
bounded program-reasoning profile. It does not infer curriculum from an opaque
natural-language objective and does not claim cross-domain or empathy training.

Every candidate is generated by the existing TRAIN-only trusted source and
checked by a local independent register interpreter. Private heldout patterns
are neither imported nor consumed. A failure to obtain a valid profile within
the bounded candidate budget fails closed instead of quietly widening scope.
"""

from __future__ import annotations

from hashlib import sha256
import re

from .maze import Challenge
from .program_maze import generate_program_challenges
from .regenerative_maze import MazeRoom
from .training_scope import TrainingScopeSpec


MAX_CANDIDATES = 256
FOCAL_STRUCTURE = "MUL A C;SUB B A;ADD B C;ADD A B"
_INITIAL = re.compile(r"(?m)^Initial registers: A=(\d+), B=(\d+)$")
_INSTRUCTION = re.compile(r"(?m)^(\d+)\. (ADD|SUB|MUL) ([AB]) ([AB]|\d+)$")
_FOCUS = {
    1: "mixed_3_to_4_instruction_structures",
    2: "four_step_register_programs",
    3: "four_step_cross_register_dependency_path",
    4: "dependency_path_with_multiple_modulo_wraps",
    5: "dependency_path_wrapping_both_registers",
}


def semantic_focus_profile(specificity: int) -> str:
    """Return the concrete program-reasoning focus declared by 1..5.

    This is NOT a universal mapping from specificity to intelligence or task
    difficulty. It is one explicit, testable skill-provider contract.
    """
    if type(specificity) is not int or specificity not in _FOCUS:
        raise ValueError("semantic specificity must be an integer in [1,5]")
    return _FOCUS[specificity]


def _replay_program(case: Challenge) -> tuple[int, int, frozenset[str]]:
    """Compute answer, instruction count and targets experiencing wraparound."""
    start = _INITIAL.search(case.prompt)
    if start is None:
        raise ValueError("trusted program generator emitted an unparseable initial state")
    registers = {"A": int(start.group(1)), "B": int(start.group(2))}
    if any(not 0 <= value < 97 for value in registers.values()):
        raise ValueError("out-of-range initial register")
    wrapped: set[str] = set()
    instructions = list(_INSTRUCTION.finditer(case.prompt))
    if not 3 <= len(instructions) <= 4:
        raise ValueError("unexpected training program length")
    for position, found in enumerate(instructions, 1):
        ordinal, operator, target, operand = found.groups()
        if int(ordinal) != position:
            raise ValueError("out-of-order instruction in approved generator")
        other = registers[operand] if operand in registers else int(operand)
        if operator == "ADD":
            raw = registers[target] + other
        elif operator == "SUB":
            raw = registers[target] - other
        else:
            raw = registers[target] * other
        if not 0 <= raw < 97:
            wrapped.add(target)
        registers[target] = raw % 97
    if str(registers["A"]) != case.answer:
        raise ValueError("approved program source disagrees with independently replayed answer")
    return registers["A"], len(instructions), frozenset(wrapped)


def generate_semantic_program_challenge(
    scope: TrainingScopeSpec,
    room: MazeRoom,
) -> Challenge:
    """Select a fresh TRAIN-only program case matching the declared focus.

    The host must pass a room already verified as belonging to the authorized
    MazePlan; this provider does not own maze provenance or score the trainee.
    Its returned Challenge includes the private gold and MUST stay trainer-side.

    Specificity narrows along a documented nested path:
      1: public training structures, 3 or 4 instructions;
      2: four instructions only;
      3: a cross-register dependency path, MUL A -> SUB B A -> ADD B -> ADD A B;
      4: the same path with >= 2 modular wraparound operations;
      5: the same path with wraparound affecting both A and B.

    These are structure/content restrictions, not just textual labels or counts.
    """
    if not isinstance(scope, TrainingScopeSpec):
        raise ValueError("scope must be a TrainingScopeSpec")
    TrainingScopeSpec.__post_init__(scope)
    if not isinstance(room, MazeRoom):
        raise ValueError("room must be a MazeRoom")
    MazeRoom.__post_init__(room)
    if room.skill != "program_reasoning" or room.skill not in scope.skills:
        raise ValueError("semantic provider supports only declared program_reasoning skill")

    profile = semantic_focus_profile(scope.specificity)
    tag = f"semantic-program-focus-v1\x1f{scope.fingerprint}\x1f{room.room_id}\x1f{room.case_seed}"
    source_seed = int.from_bytes(sha256(tag.encode("utf-8")).digest()[:8], "big") % (2**31)
    cases = generate_program_challenges(source_seed, MAX_CANDIDATES, "train")
    for case in cases:
        metadata = dict(case.metadata)
        if (case.split != "train" or case.kind != "register_program" or case.tier != 4
                or metadata.get("generator") != "labyrinth-program-v1"
                or metadata.get("profile") != "train"):
            raise ValueError("unexpected non-training challenge from approved generator")
        _answer, instruction_count, wrapped = _replay_program(case)
        structure = metadata["structure"]
        if scope.specificity >= 2 and instruction_count != 4:
            continue
        if scope.specificity >= 3 and structure != FOCAL_STRUCTURE:
            continue
        if scope.specificity >= 4:
            # Source presents four operations. A wrap event is a modular
            # reduction that changes an intermediate arithmetic value.
            # The independent replay records which register was affected.
            wraps = _count_wrap_events(case)
            if wraps < 2:
                continue
        else:
            wraps = 0
        if scope.specificity == 5 and wrapped != frozenset(("A", "B")):
            continue
        return Challenge(
            id=case.id,
            kind=case.kind,
            tier=case.tier,
            split="train",
            prompt=case.prompt,
            answer=case.answer,
            metadata=case.metadata + (
                ("semantic_selector", "labyrinth.program-focus.v1"),
                ("specificity", str(scope.specificity)),
                ("semantic_focus", profile),
                ("wrap_events", str(wraps)),
            ),
        )
    raise ValueError("approved generator cannot satisfy declared semantic specificity within bounded budget")


def _count_wrap_events(case: Challenge) -> int:
    """Count modular reductions changing raw values, independently of gold."""
    start = _INITIAL.search(case.prompt)
    if start is None:
        raise ValueError("missing register state")
    registers = {"A": int(start.group(1)), "B": int(start.group(2))}
    count = 0
    for found in _INSTRUCTION.finditer(case.prompt):
        _index, operator, target, operand = found.groups()
        other = registers[operand] if operand in registers else int(operand)
        raw = ((registers[target] + other) if operator == "ADD" else
               (registers[target] - other) if operator == "SUB" else
               registers[target] * other)
        count += not 0 <= raw < 97
        registers[target] = raw % 97
    return count
