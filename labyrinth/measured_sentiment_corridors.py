"""Opt-in TRAIN-only sentiment scheduling from a measured Minotaur weakness.

This is an executable *batch selector*, not a model trainer. It consumes the
development-only `MinotaurDevelopmentFeedback` returned by the signed-scoring
source gate, checks its Maze/cycle/skill identities, and selects only examples
already generated by the approved two-cycle MiniLM Maze. It cannot inspect
development prompts, answers, or any final examination. The same immutable
schedule must be applied to every compared training-control arm.

No host signing-key custody, event consumption, physical optimizer execution,
transfer effectiveness, or graduation authority is established here. A caller
can forge an in-process feedback dataclass/flag; an independently controlled
host must obtain it from the original signed verifier and bind the associated
learner checkpoint before invoking this opt-in scheduler.

The bounded teaching heuristics are deliberately modest: `practice` samples
shorter TRAIN templates more often; `transfer` samples longer TRAIN templates
more often; `contrast` alternates both polarity skills. Text length is only an
unvalidated difficulty proxy, NOT a measured semantic transfer challenge.
"""

from __future__ import annotations

from dataclasses import dataclass
from hashlib import sha256
from .measured_weakness_feedback import MeasuredRemediation
from .minotaur_development_feedback import (
    MinotaurDevelopmentFeedback, SkillDevelopmentObservation,
)
from .training_scope import TrainingScopeSpec
from scripts.qualify_maze_conditioned_minilm_cpu import (
    SKILLS, TrainingCycle, TrainingExample, build_training_cycles,
    validate_scope,
)


APPROVED_TACTICS = frozenset(("practice", "contrast", "transfer"))


@dataclass(frozen=True)
class MeasuredSentimentCorridor:
    """Immutable per-step TRAIN exposure batches for matched neural arms."""

    cycle: TrainingCycle
    source_event_id: str
    source_exam_id: str
    weak_skill: str
    tactic: str
    batches: tuple[tuple[TrainingExample, ...], ...]
    class_counts_per_batch: tuple[tuple[int, int], ...]
    unique_training_exposures: int
    source_signature_host_attested: bool = False
    model_execution_authenticated: bool = False
    prior_skill_transfer_qualified: bool = False
    graduation_authorized: bool = False


def _ordered(rows: tuple[TrainingExample, ...], *, tactic: str) -> tuple[TrainingExample, ...]:
    # Stable local ordering; Python's process-global RNG is never touched.
    if tactic == "practice":
        return tuple(sorted(rows, key=lambda r: (len(r.prompt), r.exposure_id)))
    if tactic == "transfer":
        return tuple(sorted(rows, key=lambda r: (-len(r.prompt), r.exposure_id)))
    return tuple(sorted(rows, key=lambda r: (
        sha256(("contrast\0" + r.exposure_id).encode("ascii")).hexdigest(),
        r.exposure_id,
    )))


def plan_measured_sentiment_corridor(
    scope: TrainingScopeSpec,
    feedback: MinotaurDevelopmentFeedback,
    *,
    steps_per_cycle: int = 16,
) -> MeasuredSentimentCorridor:
    """Use one validated weak-skill development tactic to schedule new TRAIN.

    The source verifier's signed output must have been obtained upstream;
    checking the dataclass flag cannot establish independent host custody.
    This function validates deterministic Maze lineage and only *reads* the
    learner-independent TRAIN examples. No checkpoint field is altered.
    """
    validate_scope(scope)
    if (type(feedback) is not MinotaurDevelopmentFeedback
            or type(steps_per_cycle) is not int
            or not 4 <= steps_per_cycle <= 16
            or not feedback.source_signature_verified
            or feedback.graduation_authorized
            or feedback.model_execution_authenticated
            or feedback.evaluator_host_independence_verified
            or feedback.matched_control_benefit_verified):
        raise ValueError("bounded in-process signed development feedback required")
    remediation = feedback.remediation
    if (type(remediation) is not MeasuredRemediation
            or feedback.exam_id != remediation.exam_id
            or feedback.event_id != remediation.event_id
            or feedback.from_cycle != remediation.from_cycle
            or feedback.to_cycle != remediation.to_cycle
            or feedback.from_cycle != 0 or feedback.to_cycle != 1
            or remediation.graduation_authorized
            or remediation.model_execution_authenticated
            or remediation.evaluator_host_independence_verified
            or type(remediation.weak_skills) is not tuple
            or len(remediation.weak_skills) != 1
            or remediation.weak_skills[0] not in SKILLS):
        raise ValueError("measured successor and polarity skill identities mismatch")
    if (type(feedback.observations) is not tuple
            or len(feedback.observations) != len(SKILLS)
            or any(type(obs) is not SkillDevelopmentObservation
                   for obs in feedback.observations)
            or tuple(obs.skill for obs in feedback.observations) != SKILLS):
        raise ValueError("per-polarity measured development scores required")
    weak = remediation.weak_skills[0]
    for observation in feedback.observations:
        expected_weak = observation.skill == weak
        if (observation.weak is not expected_weak
                or (observation.suggested_train_tactic is not None
                    and type(observation.suggested_train_tactic) is not str)
                or (observation.suggested_train_tactic in APPROVED_TACTICS)
                is not expected_weak):
            raise ValueError("weakness/tactic projection is inconsistent")
    tactic = next(obs.suggested_train_tactic for obs in feedback.observations
                  if obs.skill == weak)
    if type(tactic) is not str or tactic not in APPROVED_TACTICS:
        raise ValueError("unapproved polarity training tactic")
    cycle = build_training_cycles(scope, weak_cycle_one=(weak,))[1]
    if (cycle.plan != remediation.maze
            or cycle.plan.scope_fingerprint != scope.fingerprint
            or cycle.plan.objective_id != scope.objective_id
            or cycle.plan.cycle_index != feedback.to_cycle):
        raise ValueError("signed measured Maze is not this sentiment TRAIN cycle")

    weak_rows = _ordered(tuple(row for row in cycle.examples if row.skill == weak),
                         tactic=tactic)
    other_rows = _ordered(tuple(row for row in cycle.examples if row.skill != weak),
                          tactic=tactic)
    if len(weak_rows) < 3 or len(other_rows) < 2:
        raise ValueError("insufficient TRAIN-only coverage for selected tactic")

    batches = []
    for step in range(steps_per_cycle):
        if tactic == "contrast":
            chosen = (
                weak_rows[(step * 2) % len(weak_rows)],
                other_rows[(step * 2) % len(other_rows)],
                weak_rows[(step * 2 + 1) % len(weak_rows)],
                other_rows[(step * 2 + 1) % len(other_rows)],
            )
        else:
            chosen = (
                weak_rows[(step * 3) % len(weak_rows)],
                weak_rows[(step * 3 + 1) % len(weak_rows)],
                weak_rows[(step * 3 + 2) % len(weak_rows)],
                other_rows[step % len(other_rows)],
            )
        if len({row.exposure_id for row in chosen}) != 4:
            raise ValueError("TRAIN batch contains duplicate exposure identities")
        batches.append(chosen)
    used = {row.exposure_id for batch in batches for row in batch}
    if used != {row.exposure_id for row in cycle.examples}:
        raise ValueError("bounded tactic schedule failed to visit every TRAIN case")
    return MeasuredSentimentCorridor(
        cycle=cycle, source_event_id=feedback.event_id,
        source_exam_id=feedback.exam_id, weak_skill=weak, tactic=tactic,
        batches=tuple(batches),
        class_counts_per_batch=tuple((
            sum(row.label == 0 for row in batch),
            sum(row.label == 1 for row in batch),
        ) for batch in batches),
        unique_training_exposures=len(used),
    )
